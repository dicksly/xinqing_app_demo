const LOCAL_KNOWLEDGE_ARTICLES_BY_ID = new Map(
  LOCAL_KNOWLEDGE_ARTICLES.map((article) => [article.id, article])
)

const LOCAL_KNOWLEDGE_ARTICLES_BY_SOURCE_URL = new Map(
  LOCAL_KNOWLEDGE_ARTICLES.map((article) => [normalizeSourceUrl(article.sourceUrl), article])
)

export function getLocalKnowledgeArticleById(id = '') {
  return LOCAL_KNOWLEDGE_ARTICLES_BY_ID.get(id) || null
}

export function getLocalKnowledgeArticleBySourceUrl(sourceUrl = '') {
  return LOCAL_KNOWLEDGE_ARTICLES_BY_SOURCE_URL.get(normalizeSourceUrl(sourceUrl)) || null
}

function normalizeSourceUrl(sourceUrl = '') {
  if (!sourceUrl) return ''

  try {
    const url = new URL(sourceUrl)
    url.hash = ''
    return url.toString()
  } catch {
    return sourceUrl.trim()
  }
}
